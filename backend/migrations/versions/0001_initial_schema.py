# --------------------------------------------------------------------------
# The safety gate, enforced by the database rather than by application code.
#
# This is the answer to "how do you know an agent cannot bypass your safety
# check". It holds even against raw SQL, even if a prompt is compromised, even
# if the service layer has a bug. tests/integration/test_safety_gate.py proves
# it by attempting exactly that bypass.
# --------------------------------------------------------------------------
SAFETY_TRIGGER_FN = """
CREATE OR REPLACE FUNCTION assert_safety_cleared() RETURNS trigger AS $$
DECLARE
    current_status safety_status;
BEGIN
    SELECT safety_status INTO current_status
      FROM donations
     WHERE id = NEW.donation_id;

    IF current_status IS NULL THEN
        RAISE EXCEPTION 'safety gate: donation % does not exist', NEW.donation_id
            USING ERRCODE = 'foreign_key_violation';
    END IF;

    IF current_status <> 'ELIGIBLE' THEN
        RAISE EXCEPTION
            'safety gate: donation % has safety_status=% and cannot be reserved',
            NEW.donation_id, current_status
            USING ERRCODE = 'check_violation';
    END IF;

    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
"""

SAFETY_TRIGGER = """
CREATE TRIGGER trg_safety_gate
    BEFORE INSERT ON reservations
    FOR EACH ROW
    EXECUTE FUNCTION assert_safety_cleared();
"""


